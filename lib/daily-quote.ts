/**
 * Frase per una data (yyyy-MM-dd). Il giorno successivo ha sempre la frase seguente
 * dell'elenco, quindi due giorni consecutivi non hanno mai la stessa.
 */
export function dailyQuote(isoDate: string): string {
  const [y, m, d] = isoDate.split("-").map(Number);
  const dayNumber = Math.floor(Date.UTC(y, m - 1, d) / 86_400_000);
  const n = DAILY_QUOTES.length;
  return DAILY_QUOTES[((dayNumber % n) + n) % n];
}
